/**
 * Prints the icon table for utils/mapIcons.js out of the installed lucide-react, and CHECKS the committed copy against it.
 *
 * Why a script rather than hand-copied paths: a map marker is an icon the app draws ITSELF, as an inline <svg> inside a
 * Leaflet divIcon - Leaflet needs an HTML string, not a React element, so the icon's path data has to exist as data rather
 * than as a component. Copying 24 icons' worth of path syntax by hand is 24 chances to ship a glyph with a typo in it, where
 * the symptom is an icon that draws nothing at all and looks like a styling problem.
 *
 *   node scripts/map-icon-paths.mjs            # check the committed table against lucide
 *   node scripts/map-icon-paths.mjs --print    # print what the table should be, for pasting
 */
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const ICONS_DIR = path.resolve(root, 'node_modules/lucide-react/dist/esm/icons');
// The attributes an icon node can carry that a marker actually draws with. Deliberately a list rather than "everything":
// lucide's nodes also carry renderer hints, and the point of copying is the geometry.
const KEEP_ATTRIBUTES = ['d', 'cx', 'cy', 'r', 'x', 'y', 'width', 'height', 'rx', 'ry', 'x1', 'y1', 'x2', 'y2', 'points', 'cx', 'cy'];

// Read one icon's node array straight out of lucide's own module. The file is `const __iconNode = [ ... ]` followed by a
// component wrapping it, so the array is parsed rather than imported: importing would pull React into a build script.
export const iconNodes = (name) => {
  const file = path.join(ICONS_DIR, `${name}.mjs`);
  if (!fs.existsSync(file)) return null;
  const source = fs.readFileSync(file, 'utf8');
  const start = source.indexOf('const __iconNode = [');
  if (start === -1) {
    // SOME ICONS ARE NAMES FOR OTHER ICONS: `waves` is `waves-horizontal` re-exported, and reading only the first file would
    // report the most obvious water icon as missing.
    const alias = /export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/.exec(source);
    return alias ? iconNodes(alias[1]) : null;
  }
  const open = source.indexOf('[', start);
  let depth = 0;
  let end = -1;
  for (let i = open; i < source.length; i += 1) {
    if (source[i] === '[') depth += 1;
    if (source[i] === ']') {
      depth -= 1;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end === -1) return null;
  // eslint-disable-next-line no-new-func
  const raw = new Function(`return ${source.slice(open, end).replace(/,\s*key:\s*"[^"]*"/g, '')}`)();
  return raw.map(([tag, attributes]) => {
    const kept = {};
    KEEP_ATTRIBUTES.forEach((attribute) => {
      if (attributes?.[attribute] !== undefined) kept[attribute] = attributes[attribute];
    });
    return [tag, kept];
  });
};

export const iconSource = (name) => path.join(ICONS_DIR, `${name}.mjs`);

// THE CURATED SET: what a fire department's map actually needs an icon for, and no more. A closed list rather than "any of
// lucide's two thousand", because this is a LEGEND - a station that can pick 'banana' will, and then nobody can tell what the
// dots mean. Adding one is a line here and a line in utils/mapIcons.js.
export const WANTED_ICONS = [
  'droplet', 'droplets', 'waves', 'flame', 'anchor', 'sailboat', 'truck', 'shield', 'flag', 'triangle-alert',
  'key', 'door-open', 'zap', 'cross', 'heart-pulse', 'building-2', 'warehouse', 'map-pin', 'route', 'signpost',
  'traffic-cone', 'users', 'fuel', 'radio', 'thermometer', 'tree-pine', 'mountain', 'camera', 'wind', 'snowflake',
  'ruler', 'tent', 'eye', 'plug', 'siren', 'container', 'life-buoy', 'square-parking', 'train-front', 'plane',
];

const missing = WANTED_ICONS.filter((name) => !fs.existsSync(iconSource(name)));
if (missing.length) {
  console.log(`not in this version of lucide: ${missing.join(', ')}`);
  process.exit(1);
}

const table = {};
let elements = 0;
const GEOMETRY = ['d', 'cx', 'r', 'x', 'y', 'width', 'height', 'points'];
WANTED_ICONS.forEach((name) => {
  const nodes = iconNodes(name);
  if (!nodes?.length) {
    console.log(`could not read the path data for ${name}`);
    process.exit(1);
  }
  // A GLYPH IS ONLY AS GOOD AS ITS GEOMETRY: a node whose attributes were dropped on the way in draws NOTHING, and an empty
  // shape in a legend looks like a styling bug rather than a data one. Checked here rather than trusted, because the check runs
  // in the verify gate and the trust would not.
  const bare = nodes.filter(([, attributes]) => !GEOMETRY.some((attribute) => attributes[attribute] !== undefined));
  if (bare.length) {
    console.log(`${name} has ${bare.length} element(s) with no geometry in them`);
    process.exit(1);
  }
  elements += nodes.length;
  table[name] = nodes;
});

const MODULE = path.resolve(root, 'src/utils/mapIcons.js');
const header = (version) => `// GENERATED BY scripts/map-icon-paths.mjs - do not edit by hand.
//
// The geometry of every icon a landmark type may wear, taken from lucide-react v${version} (ISC licence - see
// node_modules/lucide-react). It is DATA rather than components because a map marker is an inline <svg> this app builds and
// hands to Leaflet as an HTML string, and because the same glyph is drawn in three places - the marker, the type picker and
// the legend - out of this one table.
//
//   node scripts/map-icon-paths.mjs           checks this file against the installed lucide
//   node scripts/map-icon-paths.mjs --write   regenerates it (after adding an icon to WANTED_ICONS in the script)
//
// A glyph with a typo in it draws NOTHING and looks like a styling problem, which is why the check exists rather than a note
// asking people to be careful.
export const MAP_ICONS = {
`;

const footer = `};

// Every icon a type may name, in the order the picker shows them.
export const MAP_ICON_KEYS = Object.keys(MAP_ICONS);

// The elements to draw for an icon, or the generic pin when a type names one this build does not have - which is what keeps a
// document written by a NEWER version of the app from drawing nothing at all.
export const iconElements = (key) => MAP_ICONS[String(key || '').trim()] || MAP_ICONS['map-pin'];
`;

const body = Object.entries(table)
  .map(([name, nodes]) => `  '${name}': ${JSON.stringify(nodes)},`)
  .join('\n');

if (process.argv.includes('--write')) {
  const version = JSON.parse(fs.readFileSync(path.resolve(root, 'node_modules/lucide-react/package.json'), 'utf8')).version;
  fs.writeFileSync(MODULE, `${header(version)}${body}\n${footer}`);
  console.log(`wrote ${WANTED_ICONS.length} icons (${elements} drawable elements) to src/utils/mapIcons.js`);
} else {
  // CHECK MODE, which is what the verify harness runs: every icon in the committed table has to be the one lucide draws.
  const committed = await import(`${MODULE}?v=${Date.now()}`);
  const problems = [];
  WANTED_ICONS.forEach((name) => {
    if (JSON.stringify(committed.MAP_ICONS[name]) !== JSON.stringify(table[name])) problems.push(name);
  });
  if (committed.MAP_ICON_KEYS.length !== WANTED_ICONS.length) {
    problems.push(`the table holds ${committed.MAP_ICON_KEYS.length} icons, not ${WANTED_ICONS.length}`);
  }
  console.log(
    problems.length
      ? `FAIL the committed icon table is not lucide's: ${problems.join(', ')}`
      : `the committed icon table matches lucide: ${WANTED_ICONS.length} icons, ${elements} drawable elements`
  );
  process.exit(problems.length ? 1 : 0);
}

